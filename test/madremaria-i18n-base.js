// O DEFEITO QUE ESTE ARQUIVO CONSERTA
// ===========================================================================
// O placar de test/madremaria-i18n.test.js contava quantas chaves faltavam e
// nomeava as DEZ PRIMEIRAS. Com 250 faltando, essas dez eram sempre as mesmas —
// e por isso o placar era CEGO A REGRESSAO. Medido pelo revisor: apagar a
// traducao de 'plano.veu.raspe' no ES, uma chave JA ENTREGUE, deixava o teste
// vermelho com a MESMA mensagem e as MESMAS dez chaves. A unica pista era o
// total subir de 250 para 251 — um numero que quem le interpreta como "e o
// placar de sempre, segue".
//
// Com quatro tradutores gravando por splice nos mesmos dois arquivos, uma chave
// sobrescrita por acidente desaparecia sem deixar rastro legivel.
//
// ===========================================================================
// POR QUE UMA LISTA, E NAO UM NUMERO NEM UM AGRUPAMENTO POR PREFIXO
// ===========================================================================
// Tres desenhos foram considerados. Os dois primeiros NAO resolvem:
//
//   1. CONTAGEM POR PREFIXO ("plano: 1 faltando"). Nao distingue "nunca chegou"
//      de "estava aqui e saiu". Um prefixo que ainda tem pendencia ABSORVE a
//      perda: se 'plano' tem 3 chaves faltando e uma quarta regride, o numero
//      vira 4 e a mensagem continua dizendo a mesma coisa. E exatamente a
//      cegueira de hoje, com granularidade mais fina.
//
//   2. NOMEAR AS FALTANTES POR PREFIXO em vez das dez primeiras. Melhora a
//      leitura, mas sofre do mesmo mal: a chave que regrediu entra na lista do
//      prefixo dela sem nenhuma marca que a separe das que nunca chegaram.
//
//   3. LINHA DE BASE (esta). Uma chave que esta nesta lista e NAO esta mais
//      traduzida e, por definicao, uma REGRESSAO — nao ha como confundir com
//      obra em andamento, porque a obra em andamento nunca entrou aqui. O
//      portao a acusa em bloco SEPARADO, com nome e sobrenome, acima do placar.
//
// O custo e esta lista ter de crescer quando um tradutor entrega um lote. Isso e
// uma propriedade, nao um defeito: quem entrega copy passa a ter de DECLARAR o
// que entregou, e e essa declaracao que torna a perda visivel depois. O portao
// diz a linha exata do comando quando a lista esta atrasada.
//
// ===========================================================================
// COMO ATUALIZAR (o portao manda, nao e opcional)
